"""Goal mutation persistence, identity allocation and locks."""

from contextlib import AbstractContextManager
from typing import Any, Protocol
from goal_plus.domain.goal import GoalPlusRecord


class GoalReadState(Protocol):
    def read_goal(self, goal_plus_id: str) -> GoalPlusRecord: ...


class GoalState(GoalReadState, Protocol):
    def write_goal(self, record: GoalPlusRecord) -> None: ...
    def append_event(
        self, goal_plus_id: str, event_type: str, payload: dict[str, Any]
    ) -> None: ...
    def lock_goal(self, goal_plus_id: str) -> AbstractContextManager[None]: ...
    def lock_entrypoint(self) -> AbstractContextManager[None]: ...
    def lock_search_create(self, goal_plus_id: str, request_key: str) -> AbstractContextManager[None]: ...
    def next_goal_id(self) -> str: ...
    def new_attempt_id(self) -> str: ...
