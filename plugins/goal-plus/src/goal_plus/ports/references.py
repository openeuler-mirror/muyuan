"""Reference records and provider filesystem operations."""

from pathlib import Path
from contextlib import AbstractContextManager
from typing import Protocol
from goal_plus.domain.artifacts import ArtifactRef, ReferenceWorkspaceRecord
from goal_plus.domain.search import FrozenSpec
from goal_plus.ports.state import CandidateRecord, RunRecord


class ReferenceState(Protocol):
    def lock_run(self, run_id: str) -> AbstractContextManager[None]: ...
    def read_run(self, run_id: str) -> RunRecord: ...
    def read_frozen_spec(self, frozen_spec_id: str) -> FrozenSpec: ...
    def read_candidate(self, run_id: str, candidate_id: str) -> CandidateRecord: ...
    def read(self, run_id: str) -> list[ReferenceWorkspaceRecord]: ...
    def write(self, record: ReferenceWorkspaceRecord) -> None: ...
    def destination(self, run_id: str, session_id: str) -> Path: ...


class ReferenceWorkspace(Protocol):
    def remove(
        self, source: CandidateRecord, reference: ReferenceWorkspaceRecord
    ) -> tuple[bool, bool]: ...
    def materialize(
        self, source: CandidateRecord, artifact: ArtifactRef, destination: Path
    ) -> Path: ...
