"""Verifier persistence and terminal delivery; no Search or Allocation internals."""

from contextlib import AbstractContextManager
from typing import Protocol
from goal_plus.domain.verifier import VerifierRecord, VerifierTask, VerifierTaskState


class VerifierState(Protocol):
    def lock_run(self, run_id: str) -> AbstractContextManager[None]: ...
    def load_verifier_task(self, task_id: str) -> VerifierTask: ...
    def load_verifier_tasks(self, run_id: str | None = None, *, candidate_id: str | None = None,
                            state: VerifierTaskState | None = None) -> list[VerifierTask]: ...
    def load_verifier_records(self, run_id: str, *, candidate_id: str | None = None,
                              iteration: int | None = None, settlement_id: str | None = None) -> list[VerifierRecord]: ...
    def write_verifier_task(self, task: VerifierTask) -> None: ...
    def write_verifier_record(self, record: VerifierRecord) -> None: ...


class VerifierConsumer(Protocol):
    def __call__(self, record: VerifierRecord) -> None: ...
