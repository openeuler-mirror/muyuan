#!/usr/bin/env python3
"""Materialize a disposable Circle Packing ThinkThread Search Root."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
import shutil


EXAMPLE_ROOT = Path(__file__).resolve().parent
TEMPLATE_ROOT = EXAMPLE_ROOT.parent / "circle-packing" / "workspace-template"
HINTS_ROOT = EXAMPLE_ROOT / "candidate-hints"
SPEC_PATH = EXAMPLE_ROOT / "search-spec.json"
DEFAULT_WORKSPACE = EXAMPLE_ROOT / "workspace"
MARKER_NAME = ".circle-packing-thinkthread-example"
GENERATED_README = """# Circle Packing ThinkThread Source

This disposable Root was generated by
`examples/circle-packing-thinkthread-apply/prepare_workspace.py`.

Search candidates may edit only `initial_program.py`. The public verifier,
SearchSpec, marker, and candidate hints are frozen task inputs.
"""


def materialize_workspace(
    destination: Path, *, reset: bool = False, fork: bool = False,
) -> Path:
    destination = destination.resolve()
    marker = destination / MARKER_NAME
    if destination.exists():
        if not reset:
            raise RuntimeError(
                f"destination already exists: {destination}; use --reset to "
                "replace a workspace generated by this example"
            )
        if not marker.is_file():
            raise RuntimeError(
                f"refusing to reset unrecognized destination: {destination}"
            )
        shutil.rmtree(destination)

    destination.parent.mkdir(parents=True, exist_ok=True)
    shutil.copytree(
        TEMPLATE_ROOT,
        destination,
        ignore=shutil.ignore_patterns("README.md", "__pycache__", "*.py[cod]"),
    )
    shutil.copytree(HINTS_ROOT, destination / HINTS_ROOT.name)
    shutil.copy2(SPEC_PATH, destination / SPEC_PATH.name)
    if fork:
        spec_path = destination / SPEC_PATH.name
        spec = json.loads(spec_path.read_text(encoding="utf-8"))
        spec["strategy"].update(
            initial_context="fork", inner_agent="common", llm_validation="required",
        )
        spec_path.write_text(json.dumps(spec, indent=2) + "\n", encoding="utf-8")
    destination.joinpath("README.md").write_text(
        GENERATED_README,
        encoding="utf-8",
    )
    marker.write_text(MARKER_NAME + "\n", encoding="utf-8")
    return destination


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--destination",
        type=Path,
        default=DEFAULT_WORKSPACE,
        help="ThinkThread Root workspace to create (default: ./workspace)",
    )
    parser.add_argument(
        "--fork",
        action="store_true",
        help="prepare the shared Pi/Codex fork example with required branch audits",
    )
    parser.add_argument(
        "--reset",
        action="store_true",
        help="replace only a workspace previously generated by this script",
    )
    arguments = parser.parse_args()

    try:
        destination = materialize_workspace(
            arguments.destination,
            reset=arguments.reset,
            fork=arguments.fork,
        )
    except (OSError, RuntimeError) as exc:
        parser.error(str(exc))

    print(f"workspace={destination}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
