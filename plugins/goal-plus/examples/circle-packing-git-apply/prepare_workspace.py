#!/usr/bin/env python3
"""Materialize the Circle Packing task as a writable standalone Git source."""

from __future__ import annotations

import argparse
from pathlib import Path
import shutil
import subprocess


EXAMPLE_ROOT = Path(__file__).resolve().parent
TEMPLATE_ROOT = EXAMPLE_ROOT.parent / "circle-packing" / "workspace-template"
DEFAULT_WORKSPACE = EXAMPLE_ROOT / "workspace"
MARKER_NAME = "goal-plus-circle-packing-git-apply"
GENERATED_README = """# Circle Packing Writable Git Source

This standalone Git repository was generated by
`examples/circle-packing-git-apply/prepare_workspace.py`.

Goal Plus may edit `initial_program.py` in candidate worktrees and apply the
selected publication commit back to this repository. The public verifier under
`.goal-plus-verifiers/` is frozen task infrastructure and must not be changed.
"""


def _git(workspace: Path, *arguments: str) -> str:
    completed = subprocess.run(
        ["git", "-C", str(workspace), *arguments],
        check=True,
        capture_output=True,
        text=True,
    )
    return completed.stdout.strip()


def _marker(workspace: Path) -> Path:
    return workspace / ".git" / MARKER_NAME


def materialize_workspace(destination: Path, *, reset: bool = False) -> str:
    destination = destination.resolve()
    if destination.exists():
        if not reset:
            raise RuntimeError(
                f"destination already exists: {destination}; use --reset to "
                "replace a workspace generated by this example"
            )
        if not _marker(destination).is_file():
            raise RuntimeError(
                f"refusing to reset unrecognized destination: {destination}"
            )
        shutil.rmtree(destination)

    destination.parent.mkdir(parents=True, exist_ok=True)
    shutil.copytree(TEMPLATE_ROOT, destination)
    try:
        (destination / "README.md").write_text(GENERATED_README, encoding="utf-8")
        subprocess.run(
            ["git", "init", "-q", str(destination)],
            check=True,
            capture_output=True,
            text=True,
        )
        _git(destination, "add", "-A")
        _git(
            destination,
            "-c",
            "user.name=goal-plus-example",
            "-c",
            "user.email=goal-plus@example.invalid",
            "commit",
            "-q",
            "--no-verify",
            "-m",
            "circle packing baseline",
        )
        _marker(destination).write_text(MARKER_NAME + "\n", encoding="utf-8")
        if _git(destination, "status", "--porcelain=v1", "--untracked-files=all"):
            raise RuntimeError("generated workspace is not clean")
        return _git(destination, "rev-parse", "HEAD")
    except Exception:
        shutil.rmtree(destination, ignore_errors=True)
        raise


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--destination",
        type=Path,
        default=DEFAULT_WORKSPACE,
        help="standalone Git source to create (default: ./workspace)",
    )
    parser.add_argument(
        "--reset",
        action="store_true",
        help="replace only a destination previously generated by this script",
    )
    arguments = parser.parse_args()

    try:
        baseline = materialize_workspace(
            arguments.destination,
            reset=arguments.reset,
        )
    except (OSError, RuntimeError, subprocess.CalledProcessError) as exc:
        parser.error(str(exc))

    print(f"workspace={arguments.destination.resolve()}")
    print(f"baseline={baseline}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
